LANG_FLAGS = {"ru": "🇷🇺 Русский", "en": "🇬🇧 English", "de": "🇩🇪 Deutsch"}

DEFAULT_LANG = "ru"
_lang_cache: dict[int, str] = {}

async def get_lang(guild_id: int) -> str:
    if guild_id in _lang_cache:
        return _lang_cache[guild_id]
    try:
        g = await _db.get_guild(guild_id)
        lang = (g.get("language") if isinstance(g, dict) else None) or DEFAULT_LANG
    except Exception:
        lang = DEFAULT_LANG
    if lang not in STRINGS:
        lang = DEFAULT_LANG
    _lang_cache[guild_id] = lang
    return lang

def t_sync(lang: str, key: str) -> str:
    return STRINGS.get(lang, STRINGS[DEFAULT_LANG]).get(key, STRINGS[DEFAULT_LANG].get(key, key))

async def t(guild_id: int, key: str) -> str:
    lang = await get_lang(guild_id)
    return t_sync(lang, key)

def set_lang_cache(guild_id: int, lang: str):
    _lang_cache[guild_id] = lang
